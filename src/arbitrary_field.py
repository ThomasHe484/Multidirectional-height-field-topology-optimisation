class DensityElasticity(Problem):

    def __init__(self, *args, **kwargs):
        self.surface_maps = kwargs.pop("surface_maps")
        super().__init__(*args, **kwargs)

    def custom_init(self):
        self.fe = self.fes[0]
        self.fe.flex_inds = jnp.arange(len(self.fe.cells))

    def get_tensor_map(self):

        def stress(u_grad, rho):
            rho_value = jnp.clip(rho[0], 0.0, 1.0)

            youngs_modulus = (
                E_MIN
                + (E_MAX - E_MIN) * rho_value**P_SIMP
            )

            mu = youngs_modulus / (2.0 * (1.0 + POISSON_RATIO))

            lmbda = (
                youngs_modulus * POISSON_RATIO
                / (
                    (1.0 + POISSON_RATIO)
                    * (1.0 - 2.0 * POISSON_RATIO)
                )
            )

            epsilon = 0.5 * (u_grad + u_grad.T)

            sigma = (
                lmbda * jnp.trace(epsilon) * jnp.eye(3)
                + 2.0 * mu * epsilon
            )

            return sigma

        return stress

    def set_params(self, params):
        if params.ndim == 1:
            params = params[:, None]

        num_quads = self.fes[0].num_quads

        self.internal_vars = [
            jnp.repeat(
                params[:, None, :],
                num_quads,
                axis=1,
            )
        ]

    def get_surface_maps(self):
        return self.surface_maps

    def compute_compliance(self, sol):
        """
        Standard compliance definition:

            C = integral_Gamma t . u dGamma

        This matches the SIMP baseline implementation.

        JAX-FEM surface-map sign convention:
        physical traction = -surface_map.
        """

        boundary_inds = self.boundary_inds_list[0]

        _, nanson_scale = self.fe.get_face_shape_grads(boundary_inds)

        # Shape:
        # (number_of_loaded_faces, 1, nodes_per_face, 3)
        u_face_nodes = (
            sol[self.fe.cells][boundary_inds[:, 0]][:, None, :, :]
            * self.fe.face_shape_vals[
                boundary_inds[:, 1]
            ][:, :, :, None]
        )

        # Shape:
        # (number_of_loaded_faces, face_quadrature_points, 3)
        u_face = jnp.sum(u_face_nodes, axis=2)

        subset_quad_points = self.physical_surface_quad_points[0]

        neumann_fn = self.get_surface_maps()[0]

        # Recover the real physical traction.
        traction = -jax.vmap(
            jax.vmap(neumann_fn)
        )(u_face, subset_quad_points)

        compliance = jnp.sum(
            traction * u_face * nanson_scale[:, :, None]
        )

        return compliance


