def update_asymptotes(
    iteration,
    x,
    x_old,
    x_older,
    low,
    upp,
    xmin,
    xmax,
    asy_init=0.5,
    asy_incr=1.2,
    asy_decr=0.7,
):
    x = onp.asarray(x, dtype=float)
    x_old = onp.asarray(x_old, dtype=float)
    x_older = onp.asarray(x_older, dtype=float)

    low = onp.asarray(low, dtype=float)
    upp = onp.asarray(upp, dtype=float)

    xmin = onp.asarray(xmin, dtype=float)
    xmax = onp.asarray(xmax, dtype=float)

    design_range = onp.maximum(xmax - xmin, 1e-12)

    if iteration < 2:
        low_new = x - asy_init * design_range
        upp_new = x + asy_init * design_range
    else:
        change_product = (x - x_old) * (x_old - x_older)

        factor = onp.ones_like(x)
        factor = onp.where(change_product > 0.0, asy_incr, factor)
        factor = onp.where(change_product < 0.0, asy_decr, factor)

        low_new = x - factor * (x_old - low)
        upp_new = x + factor * (upp - x_old)

        low_new = onp.maximum(low_new, x - 10.0 * design_range)
        upp_new = onp.minimum(upp_new, x + 10.0 * design_range)

        low_new = onp.minimum(low_new, x - 0.01 * design_range)
        upp_new = onp.maximum(upp_new, x + 0.01 * design_range)

    return low_new, upp_new


def get_mma_coefficients(
    x,
    gradient,
    low,
    upp,
    regularization=1e-5,
):
    distance_to_upper = onp.maximum(upp - x, 1e-12)
    distance_to_lower = onp.maximum(x - low, 1e-12)

    abs_gradient = onp.abs(gradient)
    stabilizer = regularization * onp.maximum(abs_gradient, 1.0)

    p = (
        (onp.maximum(gradient, 0.0) + stabilizer)
        * distance_to_upper**2
    )

    q = (
        (onp.maximum(-gradient, 0.0) + stabilizer)
        * distance_to_lower**2
    )

    return p, q


def get_x_from_lambda(
    lam,
    p0,
    q0,
    p1,
    q1,
    low,
    upp,
    alpha,
    beta,
):
    p = onp.maximum(p0 + lam * p1, 1e-30)
    q = onp.maximum(q0 + lam * q1, 1e-30)

    sqrt_p = onp.sqrt(p)
    sqrt_q = onp.sqrt(q)

    x_new = (
        sqrt_p * low
        + sqrt_q * upp
    ) / (sqrt_p + sqrt_q)

    x_new = onp.clip(x_new, alpha, beta)

    return x_new


def mma_subproblem(
    x,
    f0,
    df0,
    f1,
    df1,
    xmin,
    xmax,
    low,
    upp,
    move=0.03,
    dual_tolerance=1e-9,
    max_dual_iterations=100,
):
    del f0

    x = onp.asarray(x, dtype=float)
    df0 = onp.asarray(df0, dtype=float)
    df1 = onp.asarray(df1, dtype=float)

    xmin = onp.asarray(xmin, dtype=float)
    xmax = onp.asarray(xmax, dtype=float)

    low = onp.asarray(low, dtype=float)
    upp = onp.asarray(upp, dtype=float)

    arrays = [x, df0, df1, xmin, xmax, low, upp]

    if not all(arr.shape == x.shape for arr in arrays):
        raise ValueError("All MMA arrays must have the same shape.")

    if not onp.all(onp.isfinite(x)):
        raise ValueError("Current design contains NaN or Inf.")

    if not onp.all(onp.isfinite(df0)):
        raise ValueError("Objective gradient contains NaN or Inf.")

    if not onp.all(onp.isfinite(df1)):
        raise ValueError("Constraint gradient contains NaN or Inf.")

    if not onp.isfinite(f1):
        raise ValueError("Constraint value contains NaN or Inf.")

    design_range = onp.maximum(xmax - xmin, 1e-12)

    alpha = onp.maximum.reduce(
        [
            xmin,
            x - move * design_range,
            low + 0.1 * (x - low),
        ]
    )

    beta = onp.minimum.reduce(
        [
            xmax,
            x + move * design_range,
            upp - 0.1 * (upp - x),
        ]
    )

    invalid_bounds = alpha >= beta
    midpoint = 0.5 * (alpha + beta)

    alpha = onp.where(
        invalid_bounds,
        midpoint - 5e-7 * design_range,
        alpha,
    )

    beta = onp.where(
        invalid_bounds,
        midpoint + 5e-7 * design_range,
        beta,
    )

    alpha = onp.maximum(alpha, xmin)
    beta = onp.minimum(beta, xmax)

    p0, q0 = get_mma_coefficients(
        x,
        df0,
        low,
        upp,
    )

    p1, q1 = get_mma_coefficients(
        x,
        df1,
        low,
        upp,
    )

    distance_to_upper = onp.maximum(upp - x, 1e-12)
    distance_to_lower = onp.maximum(x - low, 1e-12)

    constraint_constant = (
        onp.sum(
            p1 / distance_to_upper
            + q1 / distance_to_lower
        )
        - float(f1)
    )

    def approximate_constraint(x_trial):
        return (
            onp.sum(
                p1 / onp.maximum(upp - x_trial, 1e-12)
                + q1 / onp.maximum(x_trial - low, 1e-12)
            )
            - constraint_constant
        )

    x_lambda_zero = get_x_from_lambda(
        0.0,
        p0,
        q0,
        p1,
        q1,
        low,
        upp,
        alpha,
        beta,
    )

    if approximate_constraint(x_lambda_zero) <= 0.0:
        return x_lambda_zero

    lambda_low = 0.0
    lambda_high = 1.0

    x_high = get_x_from_lambda(
        lambda_high,
        p0,
        q0,
        p1,
        q1,
        low,
        upp,
        alpha,
        beta,
    )

    feasible_lambda_found = False

    for _ in range(60):
        if approximate_constraint(x_high) <= 0.0:
            feasible_lambda_found = True
            break

        lambda_high *= 10.0

        x_high = get_x_from_lambda(
            lambda_high,
            p0,
            q0,
            p1,
            q1,
            low,
            upp,
            alpha,
            beta,
        )

    if not feasible_lambda_found:
        return x_high

    x_middle = x_high

    for _ in range(max_dual_iterations):
        lambda_middle = 0.5 * (lambda_low + lambda_high)

        x_middle = get_x_from_lambda(
            lambda_middle,
            p0,
            q0,
            p1,
            q1,
            low,
            upp,
            alpha,
            beta,
        )

        constraint_value = approximate_constraint(x_middle)

        if abs(constraint_value) <= dual_tolerance:
            break

        if constraint_value > 0.0:
            lambda_low = lambda_middle
        else:
            lambda_high = lambda_middle

    return x_middle


