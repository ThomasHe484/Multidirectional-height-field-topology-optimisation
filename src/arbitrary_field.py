# 7. Height-field to density mapping
# ============================================================

def compute_density_from_directional_height_fields(
    h_fields,
    points,
):
    """
    Convert arbitrary-direction cutting-front fields into nodal density.

    A direction vector points inward from its supporting stock plane.  The
    field is interpolated on the corresponding normal plane.  A point survives
    only when it lies behind every directional cutting front.
    """

    rho = jnp.ones(points.shape[0], dtype=jnp.float64)

    for field, spec in zip(h_fields, FIELD_SPECS):
        direction = jnp.asarray(spec["direction"])
        u_axis = jnp.asarray(spec["u_axis"])
        v_axis = jnp.asarray(spec["v_axis"])

        q_coordinate = points @ direction
        s_coordinate = points @ u_axis
        t_coordinate = points @ v_axis

        interpolation_coordinates = jnp.stack([
            (s_coordinate - spec["s_min_mm"]) / spec["spacing_s_mm"],
            (t_coordinate - spec["t_min_mm"]) / spec["spacing_t_mm"],
        ])

        cutting_front = jax.scipy.ndimage.map_coordinates(
            field,
            interpolation_coordinates,
            order=1,
            mode="nearest",
        )

        distance_from_supporting_plane = (
            q_coordinate - spec["q_min_mm"]
        )
        survives_direction = 0.5 * (
            jnp.tanh(
                BETA
                * (distance_from_supporting_plane - cutting_front)
            )
            + 1.0
        )

        rho = rho * survives_direction

    return rho


