def normalise_vector(vector, label):
    """Return a finite unit vector or fail with a configuration error."""

    result = onp.asarray(vector, dtype=float)
    if result.shape != (3,) or not onp.all(onp.isfinite(result)):
        raise ValueError(f"{label} must contain three finite components.")

    magnitude = float(onp.linalg.norm(result))
    if magnitude <= 1.0e-12:
        raise ValueError(f"{label} must not be the zero vector.")

    return result / magnitude


def rotate_vector_rodrigues(vector, axis, angle_degrees):
    """Rotate a vector around an axis using the right-hand convention."""

    vector = normalise_vector(vector, "rotary reference direction")
    axis = normalise_vector(axis, "rotary axis")
    angle = onp.deg2rad(float(angle_degrees))

    rotated = (
        vector * onp.cos(angle)
        + onp.cross(axis, vector) * onp.sin(angle)
        + axis * onp.dot(axis, vector) * (1.0 - onp.cos(angle))
    )

    return normalise_vector(rotated, "rotated cutting direction")


def get_configured_cut_directions():
    """Return ordered (name, inward unit vector) direction pairs."""

    if DIRECTION_MODE == "rotary":
        axis = normalise_vector(ROTARY_AXIS_VECTOR, "rotary axis")
        reference = normalise_vector(
            ROTARY_REFERENCE_DIRECTION,
            "rotary reference direction",
        )

        if abs(float(onp.dot(axis, reference))) > 1.0 - 1.0e-10:
            raise ValueError(
                "ROTARY_REFERENCE_DIRECTION must not be parallel to "
                "ROTARY_AXIS_VECTOR."
            )

        directions = [
            (
                f"a{float(angle) % 360.0:06.2f}",
                rotate_vector_rodrigues(reference, axis, angle),
            )
            for angle in ROTARY_ANGLES_DEG
        ]
    elif DIRECTION_MODE == "vectors":
        directions = [
            (str(name), normalise_vector(vector, f"direction {name}"))
            for name, vector in DIRECT_CUT_DIRECTIONS
        ]
    else:
        raise ValueError(
            "DIRECTION_MODE must be either 'rotary' or 'vectors'."
        )

    if len(directions) == 0:
        raise ValueError("At least one cutting direction is required.")

    names = [name for name, _ in directions]
    if len(set(names)) != len(names):
        raise ValueError("Cutting-direction names must be unique.")

    for i, (_, direction_i) in enumerate(directions):
        for _, direction_j in directions[:i]:
            if float(onp.dot(direction_i, direction_j)) > 1.0 - 1.0e-10:
                raise ValueError(
                    "Duplicate cutting directions were generated.  Remove "
                    "repeated rotary angles or repeated direct vectors."
                )

    return directions


def choose_normal_plane_basis(direction):
    """Choose deterministic orthonormal u-v axes normal to direction."""

    direction = normalise_vector(direction, "cutting direction")
    tolerance = 1.0e-10

    # Preserve the original field coordinates for the six cardinal cases.
    if abs(abs(direction[0]) - 1.0) <= tolerance:
        return (
            onp.asarray([0.0, 1.0, 0.0]),
            onp.asarray([0.0, 0.0, 1.0]),
        )
    if abs(abs(direction[1]) - 1.0) <= tolerance:
        return (
            onp.asarray([1.0, 0.0, 0.0]),
            onp.asarray([0.0, 0.0, 1.0]),
        )
    if abs(abs(direction[2]) - 1.0) <= tolerance:
        return (
            onp.asarray([1.0, 0.0, 0.0]),
            onp.asarray([0.0, 1.0, 0.0]),
        )

    coordinate_axes = onp.eye(3)
    reference = coordinate_axes[int(onp.argmin(onp.abs(direction)))]
    u_axis = reference - onp.dot(reference, direction) * direction
    u_axis = normalise_vector(u_axis, "normal-plane u axis")
    v_axis = normalise_vector(
        onp.cross(direction, u_axis),
        "normal-plane v axis",
    )

    return u_axis, v_axis


def build_direction_field_specs():
    """Build static interpolation grids for every prescribed direction."""

    specs = []
    start = 0

    for name, direction in get_configured_cut_directions():
        u_axis, v_axis = choose_normal_plane_basis(direction)

        q_corner = BOX_CORNERS @ direction
        s_corner = BOX_CORNERS @ u_axis
        t_corner = BOX_CORNERS @ v_axis

        q_min = float(onp.min(q_corner))
        q_max = float(onp.max(q_corner))
        s_min = float(onp.min(s_corner))
        s_max = float(onp.max(s_corner))
        t_min = float(onp.min(t_corner))
        t_max = float(onp.max(t_corner))

        num_s = max(
            2,
            int(onp.ceil((s_max - s_min) / HEIGHT_FIELD_GRID_SPACING_MM))
            + 1,
        )
        num_t = max(
            2,
            int(onp.ceil((t_max - t_min) / HEIGHT_FIELD_GRID_SPACING_MM))
            + 1,
        )

        spacing_s = (s_max - s_min) / (num_s - 1)
        spacing_t = (t_max - t_min) / (num_t - 1)
        field_size = num_s * num_t
        projected_depth = q_max - q_min

        specs.append({
            "name": name,
            "direction": direction,
            "u_axis": u_axis,
            "v_axis": v_axis,
            "q_min_mm": q_min,
            "q_max_mm": q_max,
            "projected_stock_depth_mm": projected_depth,
            "s_min_mm": s_min,
            "s_max_mm": s_max,
            "t_min_mm": t_min,
            "t_max_mm": t_max,
            "shape": (num_s, num_t),
            "spacing_s_mm": spacing_s,
            "spacing_t_mm": spacing_t,
            "size": field_size,
            "slice": slice(start, start + field_size),
            "maximum_front_mm": (
                projected_depth + SMOOTH_TRANSITION_MARGIN_MM
            ),
        })

        start += field_size

    return tuple(specs), start


