# 5. Differentiable 2D Gaussian filter
# ============================================================

def make_physical_gaussian_kernel_2d(spec):
    """Build a Gaussian kernel using each rotated grid's real spacing."""

    spacing_s = spec["spacing_s_mm"]
    spacing_t = spec["spacing_t_mm"]
    radius_s = int(onp.ceil(GAUSSIAN_FILTER_RADIUS_MM / spacing_s))
    radius_t = int(onp.ceil(GAUSSIAN_FILTER_RADIUS_MM / spacing_t))

    offset_s = onp.arange(-radius_s, radius_s + 1) * spacing_s
    offset_t = onp.arange(-radius_t, radius_t + 1) * spacing_t
    squared_radius = (
        offset_s[:, None] ** 2
        + offset_t[None, :] ** 2
    )
    kernel = onp.exp(
        -0.5 * squared_radius / GAUSSIAN_FILTER_SIGMA_MM**2
    )
    kernel /= onp.sum(kernel)

    return jnp.asarray(kernel), radius_s, radius_t


for _spec in FIELD_SPECS:
    (
        _spec["gaussian_kernel"],
        _spec["gaussian_radius_s_cells"],
        _spec["gaussian_radius_t_cells"],
    ) = make_physical_gaussian_kernel_2d(_spec)


def gaussian_filter_2d(height_field, spec):
    """Apply an edge-padded differentiable Gaussian in physical units."""

    radius_s = spec["gaussian_radius_s_cells"]
    radius_t = spec["gaussian_radius_t_cells"]
    padded_field = jnp.pad(
        height_field,
        ((radius_s, radius_s), (radius_t, radius_t)),
        mode="edge",
    )

    return jax.scipy.signal.convolve(
        padded_field,
        spec["gaussian_kernel"],
        mode="valid",
    )


