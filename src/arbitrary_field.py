def validate_direction_field_specs():
    """Run cheap geometry checks before JAX compilation or FEM assembly."""

    expected_start = 0

    for spec in FIELD_SPECS:
        direction = spec["direction"]
        u_axis = spec["u_axis"]
        v_axis = spec["v_axis"]

        if not onp.isclose(onp.linalg.norm(direction), 1.0, atol=1.0e-10):
            raise ValueError(f"Direction {spec['name']} is not a unit vector.")
        if not onp.isclose(onp.linalg.norm(u_axis), 1.0, atol=1.0e-10):
            raise ValueError(f"u axis for {spec['name']} is not normalised.")
        if not onp.isclose(onp.linalg.norm(v_axis), 1.0, atol=1.0e-10):
            raise ValueError(f"v axis for {spec['name']} is not normalised.")
        if abs(float(onp.dot(direction, u_axis))) > 1.0e-10:
            raise ValueError(f"u axis for {spec['name']} is not perpendicular.")
        if abs(float(onp.dot(direction, v_axis))) > 1.0e-10:
            raise ValueError(f"v axis for {spec['name']} is not perpendicular.")
        if abs(float(onp.dot(u_axis, v_axis))) > 1.0e-10:
            raise ValueError(f"Local axes for {spec['name']} are not orthogonal.")
        if spec["slice"].start != expected_start:
            raise ValueError("Directional design-variable slices are not contiguous.")
        if spec["slice"].stop - spec["slice"].start != spec["size"]:
            raise ValueError("Directional field size and slice length disagree.")

        s_corner = BOX_CORNERS @ u_axis
        t_corner = BOX_CORNERS @ v_axis
        tolerance = 1.0e-9
        if (
            onp.min(s_corner) < spec["s_min_mm"] - tolerance
            or onp.max(s_corner) > spec["s_max_mm"] + tolerance
            or onp.min(t_corner) < spec["t_min_mm"] - tolerance
            or onp.max(t_corner) > spec["t_max_mm"] + tolerance
        ):
            raise ValueError(
                f"Normal-plane grid for {spec['name']} does not cover the stock."
            )

        expected_start = spec["slice"].stop

    if expected_start != TOTAL_NUM_DESIGN_VARIABLES:
        raise ValueError("Total directional design-variable count is inconsistent.")


