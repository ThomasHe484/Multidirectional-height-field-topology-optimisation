def assess_convergence(history_data):
    """Assess a consecutive window of updated physical designs."""

    if len(history_data) == 0:
        return {
            "converged": False,
            "enough_history": False,
            "criteria": {},
            "observed": {},
            "individual_checks": {},
        }

    enough_history = bool(
        history_data[-1]["iteration"] >= MINIMUM_ITERATIONS
        and len(history_data) >= CONVERGENCE_WINDOW
    )

    if enough_history:
        recent_rows = history_data[-CONVERGENCE_WINDOW:]

        recent_relative_changes = [
            abs(row["relative_compliance_change"])
            for row in recent_rows
        ]
        recent_density_changes = [
            abs(row["max_physical_cell_density_change"])
            for row in recent_rows
        ]

        finite_window = bool(
            all(onp.isfinite(recent_relative_changes))
            and all(onp.isfinite(recent_density_changes))
        )

        if finite_window:
            maximum_recent_relative_change = float(
                max(recent_relative_changes)
            )
            maximum_recent_density_change = float(
                max(recent_density_changes)
            )
        else:
            maximum_recent_relative_change = None
            maximum_recent_density_change = None
    else:
        finite_window = False
        maximum_recent_relative_change = None
        maximum_recent_density_change = None

    final_absolute_volume_error = float(
        abs(history_data[-1]["heightfield_nodal_volume_error"])
    )

    compliance_converged = bool(
        enough_history
        and finite_window
        and maximum_recent_relative_change
        <= COMPLIANCE_RELATIVE_TOLERANCE
    )
    density_converged = bool(
        enough_history
        and finite_window
        and maximum_recent_density_change
        <= MAX_PHYSICAL_DENSITY_CHANGE_TOLERANCE
    )
    volume_converged = bool(
        final_absolute_volume_error
        <= VOLUME_ABSOLUTE_TOLERANCE
    )

    converged = bool(
        compliance_converged
        and density_converged
        and volume_converged
    )

    return {
        "converged": converged,
        "enough_history": enough_history,
        "minimum_iterations": MINIMUM_ITERATIONS,
        "window_length": CONVERGENCE_WINDOW,
        "criteria": {
            "maximum_recent_relative_compliance_change":
                COMPLIANCE_RELATIVE_TOLERANCE,
            "maximum_recent_physical_cell_density_change":
                MAX_PHYSICAL_DENSITY_CHANGE_TOLERANCE,
            "final_absolute_heightfield_nodal_volume_error":
                VOLUME_ABSOLUTE_TOLERANCE,
        },
        "observed": {
            "maximum_recent_relative_compliance_change":
                maximum_recent_relative_change,
            "maximum_recent_physical_cell_density_change":
                maximum_recent_density_change,
            "final_absolute_heightfield_nodal_volume_error":
                final_absolute_volume_error,
        },
        "individual_checks": {
            "compliance_converged": compliance_converged,
            "physical_density_converged": density_converged,
            "volume_converged": volume_converged,
        },
    }


