"""
Arbitrary-direction height-field topology optimisation of a 3D cantilever.

The finite-element problem is unchanged from the supplied six-height-field
cantilever: a 160 x 40 x 40 mm aluminium beam, an 80 x 20 x 20 HEX8 mesh,
100 N downward end loading, compliance minimisation and a 0.40 nodal-volume
target.  Only the subtractive design parameterisation has been generalised.

Each prescribed inward cutting direction d owns a two-dimensional height field
on a plane normal to d.  For a point x, q = x.d is its coordinate along the
cutting direction and (s, t) are its coordinates on the normal plane.  The
interpolated field h_d(s, t) is the position of the cutting front measured from
the supporting plane q_min of the rectangular stock.  Material survives a
directional cut when q - q_min is greater than h_d(s, t).  The final density is
the smooth product of the survival functions for every prescribed direction.

Directions may be entered directly as arbitrary vectors or generated by
rotating a reference cutting direction about a specified rotary axis.  The
default configuration uses eight 45-degree indexed orientations about x, which
is a discrete A-axis machining model.  Changing the direction list does not
require changes to the FEM mesh, load or boundary conditions.

No cutter diameter, ball-end envelope, neck length, holder collision or maximum
insertion-depth constraint is used.  Height bounds merely span the complete
stock projection plus a smooth-Heaviside margin; they are numerical bounds, not
tool-geometry restrictions.  The optional 2D Gaussian height-field filter is
retained as a surface regulariser.

This is a machining-direction-aware geometry model, not a complete CNC process
simulation.  Tool paths, fixtures, machine travel and collision checking are
outside its scope.
"""

